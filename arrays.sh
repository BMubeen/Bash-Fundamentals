#!/bin/bash
# What is it?
# An array is a variable that can store multiple values.
# Each value is stored at an index (position).
# How it works:
# Arrays are created using parentheses ()
# Example: fruits=("apple" "banana" "orange")
# Index starts at 0
# Rules:
# - Use ${array[index]} to access values
# - Index starts at 0
# - Use ${array[@]} to access all values
# Common mistakes:
# forgetting parentheses ()
# Wrong index number
# missing $ when accessing values
# Troubleshooting:
# - Check index values (start at 0)
# - Use echo to print array contents
# - Make sure syntax is correct