#!/bin/bash
# What is it?
# A while loop repeats code while a condition is true.
# It is useful when the number of repetitions is unknown.
# How it works :
# Repedeatly executes a block of commands as long as a specific condition evaluates to true 
# Important: 
# Bash does not have a built-in do while loop.
# It can be simulated using while loops.
# Rules : 
# - Condition is checked before eachl loop
# - Must end with done 
# - Variable must usally change to avoid infinite loops 
# Common mistakes: 
# - Forgetting done
# - not updating loop variable 
# - Infinite loops
# Trouble shooting:
# - Check that your varible chnages
# - Make sure condition becomes false 
# - Use echo to debug loop progress 
