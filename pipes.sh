# What is it? 
# A pipe sends the outut oof one command
# Directly into another command.
# How it works:
# command1 | command2
#
# command1 produces output
# command2 receives and processes it
# Rules: 
# - use | between commands
# - Output from first becomes inpur for second 
# - Multiple pipes can be chained 
# Comon mistkaes: 
# - forgetting spaces around | 
# - piping incompatible commands 
# - misunderstanding command output
# Troubleshooting: 
# - test commands separately first
# - Check command output
# - Vertex syntax